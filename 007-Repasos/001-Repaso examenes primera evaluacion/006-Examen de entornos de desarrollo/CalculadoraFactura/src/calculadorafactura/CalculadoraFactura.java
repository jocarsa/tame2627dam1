    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        // Primero tomamos datos
        String total = jTextField1.getText();
        String irpf = jTextField2.getText();
        String iva = jTextField3.getText();
        
        // Ahora convertimos a numeros
        float totaldecimal = parseFloat(total);
        float irpfdecimal = parseFloat(irpf);
        float ivadecimal = parseFloat(iva);
        
        // Ahora calculamos
        float base = totaldecimal / (1 + ivadecimal/100 - irpfdecimal/100);
        float ivafinal = base*(ivadecimal/100);
        float irpffinal = base*(irpfdecimal/100);
        
        // Pintamos en pantalla
        jLabel7.setText(base+" €");
        jLabel9.setText(irpffinal+" €");
        jLabel11.setText(ivafinal+" €");
    }//GEN-LAST:event_jButton1ActionPerformed

