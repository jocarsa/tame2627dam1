    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        // Primero atraparemos los datos
        int peso;
        peso = parseInt(jTextField1.getText());
        float altura;
        altura = parseFloat(jTextField2.getText());
        // Luego realizaremos cálculos
        float imc = peso / (altura*altura);
        String mensaje = "";
        if(imc <= 16){
            mensaje = "Delgadez severa";
        }else if(imc > 16 && imc <= 17){
            mensaje = "Delgadez moderada";
        }else if(imc > 17 && imc <= 18.4){
            mensaje = "Delgadez leve";
        }else if(imc > 18.4 && imc <= 24.9){
            mensaje = "Peso normal";
        }else if(imc > 24.9 && imc <= 29.9){
            mensaje = "Sobrepeso";
        }else if(imc > 29.9 && imc <= 34.9){
            mensaje = "Obesidad grado I";
        }else if(imc > 34.9 && imc <= 39.9){
            mensaje = "Obesidad grado II";
        }else if(imc > 39.9){
            mensaje = "Obesidad grado III";
        }
        
        // Y por ultimo, mostraremos resultados
        jLabel3.setText(mensaje);
    }//GEN-LAST:event_jButton1ActionPerformed

