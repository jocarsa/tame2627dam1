package proyecto007funcionessi;

public class Proyecto007FuncionesSi {
    static int suma(int operando1,int operando2){
        int suma = operando1 + operando2;
        return suma;
    }
    
    public static void main(String[] args) {
        System.out.println(suma(4,3));
        
        System.out.println(suma(6,4));
    }
    
}
